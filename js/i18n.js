let currentLanguage = 'es';

function readInitialLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get('lang');
  if (queryLanguage === 'en' || queryLanguage === 'es') return queryLanguage;
  try {
    const saved = window.localStorage.getItem('nallpa-language');
    if (saved === 'en' || saved === 'es') return saved;
  } catch {}
  return document.documentElement.lang === 'en' ? 'en' : 'es';
}

export function getLanguage() {
  return currentLanguage;
}

export function t(key, language = currentLanguage) {
  return translations[language]?.[key] ?? translations.es[key] ?? key;
}

function setTranslatedValue(element, value, useHtml = false) {
  const base = element.querySelector?.(':scope > .silver-spotlight-base');
  const overlay = element.querySelector?.(':scope > .silver-spotlight-overlay');
  if (base && overlay) {
    if (useHtml) {
      base.innerHTML = value;
      overlay.innerHTML = value;
    } else {
      base.textContent = value;
      overlay.textContent = value;
    }
    return;
  }
  if (useHtml) element.innerHTML = value;
  else element.textContent = value;
}

export function applyLanguage(language, { persist = true, updateUrl = true } = {}) {
  currentLanguage = language === 'en' ? 'en' : 'es';
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    setTranslatedValue(element, t(element.dataset.i18n), false);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    setTranslatedValue(element, t(element.dataset.i18nHtml), true);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt));
  });
  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    element.setAttribute('content', t(element.dataset.i18nContent));
  });

  const toggle = document.querySelector('[data-language-toggle]');
  if (toggle) toggle.setAttribute('aria-label', currentLanguage === 'es' ? 'Switch to English' : 'Cambiar a español');

  if (persist) {
    try { window.localStorage.setItem('nallpa-language', currentLanguage); } catch {}
  }
  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', currentLanguage);
    window.history.replaceState({}, '', `${url.pathname}${url.search}${url.hash}`);
  }
  window.dispatchEvent(new CustomEvent('nallpa:languagechange', { detail: { language: currentLanguage } }));
}

export function initI18n() {
  applyLanguage(readInitialLanguage(), { persist: false, updateUrl: false });
  document.querySelector('[data-language-toggle]')?.addEventListener('click', () => {
    applyLanguage(currentLanguage === 'es' ? 'en' : 'es');
  });
}
